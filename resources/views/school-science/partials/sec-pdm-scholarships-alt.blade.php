          <h3>Need-Based Scholarships</h3>
          <p>
            To be eligible for the need-based scholarship, the combined income of both parents/guardians of the eligible
            student — or, if the student is married, the combined income of the student and spouse — must be less than
            8.00 LPA.
          </p>
          <p>
            Candidates admitted through merit scholarship in the slabs of 75%, 60%, 40%, 25% and 15%, whose
            parents/guardians combined income is less than the prescribed limits, are eligible for the additional
            need-based scholarship.
